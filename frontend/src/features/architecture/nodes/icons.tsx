export function renderNodeIcon(iconKey?: string, size = 18, color = 'currentColor'): React.ReactNode {
  if (!iconKey) return <NodeIcons.app size={size} color={color} />;
  const normalized = iconKey.toLowerCase().trim();
  if (NodeIcons[normalized]) {
    const IconComp = NodeIcons[normalized];
    return <IconComp size={size} color={color} />;
  }
  // If it's an emoji or plain character
  if (iconKey.length <= 4) {
    return <span style={{ fontSize: `${size}px`, lineHeight: 1 }}>{iconKey}</span>;
  }
  return <NodeIcons.app size={size} color={color} />;
}
